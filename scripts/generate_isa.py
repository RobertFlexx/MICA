#!/usr/bin/env python3
"""Generate checked-in consumers of the frozen MICA 1.0 encoding allocation."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    spec = json.loads((ROOT / "isa/encodings/mica1.json").read_text())
    groups = spec["groups"]
    banner = "// Generated by scripts/generate_isa.py; edit isa/encodings/mica1.json.\n"
    asm = banner
    for name, rows in groups.items():
        ty = "std::pair<int, int>" if name == "MEM" else "int"
        asm += f"static const std::map<std::string, {ty}> {name} = {{\n"
        for r in rows:
            value = f'{{{r["op"]}, {r["bytes"]}}}' if name == "MEM" else str(r["op"])
            asm += f'  {{"{r["name"]}", {value}}},\n'
        asm += "};\n"
    names = {"R": "rnames", "MEM": "mn", "ALU": "a3", "IMM": "a3i",
             "BR": "branches", "BITOPS": "bitnames", "W32": "words",
             "MX": "qmem", "FLOW": "flow", "SYS": "sys", "V": "vec"}
    dis = banner
    for group, name in names.items():
        rows = sorted(groups[group], key=lambda r: r["op"])
        assert [r["op"] for r in rows] == list(range(len(rows)))
        dis += f"static const std::array<const char *, {len(rows)}> {name} = {{\n"
        dis += ",\n".join('  "' + r["name"] + '"' for r in rows) + "\n};\n"
    sv = banner
    for group, fmt in spec["formats"].items():
        if "major" in fmt:
            sv += f"localparam [3:0] MICA_MAJOR_{group} = 4'd{fmt['major']};\n"
        for r in groups[group]:
            name = r["name"].upper().replace(".", "_")
            sv += f"localparam integer MICA_OP_{group}_{name} = {r['op']};\n"
    for r in groups["CSRS"]:
        sv += f"localparam [7:0] MICA_CSR_{r['name'].upper()} = 8'd{r['op']};\n"
    def syntax(group, row):
        op, name = row["op"], row["name"]
        if group == "R": args = "" if op == 0 or op >= 18 else "d" if 13 <= op <= 16 else "d,s"
        elif group == "I": args = "target" if op == 7 else "d,target" if op in [5,6] else "d,imm"
        elif group in ["MEM","MX"]: args = "d,[base+offset]"
        elif group in ["ALU","W32"]: args = "d,a,b"
        elif group == "IMM": args = "d,a,imm"
        elif group == "WIDE": args = "d,imm16"
        elif group == "BR": args = "a,b,target"
        elif group == "J": args = "target"
        elif group == "LOOP": args = "counter,target"
        elif group == "FLOW": args = "d,[base],stride"
        elif group == "BITOPS": args = "d,a" if op <= 3 or op >= 17 else "d,a,b"
        elif group == "SYS": args = "d,csr" if op == 0 else "csr,a" if op == 1 else "d,[a]" if op in [2,6] else "d,b,[a]"
        elif group == "V":
            args = "vd,[a]" if op in [16,17] else "vd,va" if op in [13,14] else "vd,va,vb"
            if op not in [16,17]: name += ".uN"
        return name + (" " + args if args else "")
    doc = "# MICA 1.0 encoding allocation\n\nGenerated from `isa/encodings/mica1.json`. "
    doc += "The first halfword is little endian; for a long instruction its top two bits "
    doc += "are 11 and its bits 13:10 contain the major. Payload is "
    doc += "`((first & 1023) << 16) | second`. Unallocated encodings are illegal.\n\n"
    for group, fmt in spec["formats"].items():
        doc += f"## {group}\n\n"
        doc += (f"Short class {fmt['class']}. " if "class" in fmt else f"Extended major {fmt['major']}. ")
        doc += f"`{fmt['fields']}`\n\n| Opcode | Canonical syntax and disassembly | Extension | Execution |\n| ---: | --- | --- | --- |\n"
        for r in groups[group]:
            doc += f"| {r['op']} | `{syntax(group, r)}` | {r['extension']} | {r['semantics'].replace('|', '&#124;')} |\n"
    doc += "\nCompact F instructions use short R op8 = 23 + the FLOW opcode. "
    doc += "Extended majors 12 through 15 and all unallocated subopcodes are reserved.\n"
    profiles = json.loads((ROOT / "isa/profiles/profiles.json").read_text())["profiles"]
    profile_h = banner + "#pragma once\n#include <array>\n#include <string_view>\nnamespace mica {\nstruct Profile {std::string_view name; int width; unsigned features; bool runnable;};\ninline constexpr std::array<Profile,5> profiles={{\n"
    feature_bits = {"X":1,"M":2,"F":4,"A":8,"V":16,"B":32,"T":64}
    for name, profile in profiles.items():
        features = sum(feature_bits[x] for x in profile["extensions"])
        runnable = "false" if profile["status"].startswith("proposal") else "true"
        profile_h += f'  {{"{name}", {profile["xlen"]}, {features}, {runnable}}},\n'
    profile_h += "}};\n} // namespace mica\n"
    return {"isa/generated/assembler.inc": asm, "isa/generated/disassembler.inc": dis,
            "isa/generated/mica_isa.svh": sv, "docs/architecture/ENCODINGS.md": doc, "isa/generated/profiles.hpp": profile_h}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"stale generated file: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
