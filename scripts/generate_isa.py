#!/usr/bin/env python3
"""Generate the checked-in MICA 2.0 opcode tables, profile data and ISA map."""

import argparse
import json
from pathlib import Path

from isa_schema import patterns

ROOT = Path(__file__).resolve().parents[1]


def generate():
    spec = json.loads((ROOT / "isa/encodings/mica2.json").read_text())
    groups = spec["groups"]
    compact = json.loads((ROOT / "isa/encodings/mica2-compact.json").read_text())
    profiles = json.loads((ROOT / "isa/profiles/profiles.json").read_text())["profiles"]
    envelopes = patterns(spec, compact, profiles)
    banner = "// Generated by scripts/generate_isa.py; edit isa/encodings/mica2.json.\n"
    asm = banner
    for name, rows in groups.items():
        ty = "std::pair<int, int>" if name == "MEM" else "int"
        asm += f"static const std::map<std::string, {ty}> {name} = {{\n"
        for r in rows:
            value = f'{{{r["op"]}, {r["bytes"]}}}' if name == "MEM" else str(r["op"])
            asm += f'  {{"{r["name"]}", {value}}},\n'
        asm += "};\n"
    names = {
        "R": "rnames",
        "MEM": "mn",
        "ALU": "a3",
        "IMM": "a3i",
        "BR": "branches",
        "BITOPS": "bitnames",
        "W32": "words",
        "MX": "qmem",
        "FLOW": "flow",
        "SYS": "sys",
        "V": "vec",
    }
    dis = banner
    for group, name in names.items():
        rows = sorted(groups[group], key=lambda r: r["op"])
        assert [r["op"] for r in rows] == list(range(len(rows)))
        dis += f"static const std::array<const char *, {len(rows)}> {name} = {{\n"
        dis += ",\n".join('  "' + r["name"] + '"' for r in rows) + "\n};\n"
    sv = banner
    for group, fmt in spec["formats"].items():
        if "major" in fmt:
            sv += f"localparam [3:0] MICA_MAJOR_{group} = 4'd{fmt['major']};\n"
        for r in groups[group]:
            name = r["name"].upper().replace(".", "_")
            sv += f"localparam integer MICA_OP_{group}_{name} = {r['op']};\n"
    for r in groups["CSRS"]:
        sv += f"localparam [7:0] MICA_CSR_{r['name'].upper()} = 8'd{r['op']};\n"

    def syntax(group, row):
        op, name = row["op"], row["name"]
        if group == "R":
            args = (
                "d,[sp+slot]"
                if op in (31, 32)
                else (
                    ""
                    if op == 0 or 18 <= op <= 22
                    else "d" if 13 <= op <= 16 else "d,s"
                )
            )
        elif group == "I":
            args = "target" if op == 7 else "d,target" if op in [5, 6] else "d,imm"
        elif group in ["MEM", "MX"]:
            args = "d,[base+offset]"
        elif group in ["ALU", "W32"]:
            args = "d,a,b"
        elif group == "IMM":
            args = "d,a,imm"
        elif group == "WIDE":
            args = "d,imm16"
        elif group == "BR":
            args = "a,b,target"
        elif group == "J":
            args = "target"
        elif group == "LOOP":
            args = "counter,target"
        elif group == "FLOW":
            args = "d,[base],stride"
        elif group == "BITOPS":
            args = "d,a" if op <= 3 or op >= 17 else "d,a,b"
        elif group == "SYS":
            args = (
                "d,csr"
                if op == 0
                else "csr,a" if op == 1 else "d,[a]" if op in [2, 6] else "d,b,[a]"
            )
        elif group == "V":
            args = (
                "vd,[a]"
                if op in [16, 17]
                else "vd,va" if op in [13, 14] else "vd,va,vb"
            )
            if op not in [16, 17]:
                name += ".uN"
        return name + (" " + args if args else "")

    doc = (
        "# MICA 2.0 encoding allocation\n\nGenerated from `isa/encodings/mica2.json`. "
    )
    doc += (
        "The first halfword is little endian; for a long instruction its top two bits "
    )
    doc += "are 11 and its bits 13:10 contain the major. Payload is "
    doc += "`((first & 1023) << 16) | second`. Unallocated encodings are illegal.\n\n"
    for group, fmt in spec["formats"].items():
        doc += f"## {group}\n\n"
        doc += (
            f"Short class {fmt['class']}. "
            if "class" in fmt
            else f"Extended major {fmt['major']}. "
        )
        doc += f"`{fmt['fields']}`\n\n| Opcode | Canonical syntax and disassembly | Extension | Execution |\n| ---: | --- | --- | --- |\n"
        for r in groups[group]:
            doc += f"| {r['op']} | `{syntax(group, r)}` | {r['extension']} | {r['semantics'].replace('|', '&#124;')} |\n"
    doc += "\nFLOW opcodes 0..7 have compact forms at short R op8 = 23 + the FLOW opcode. "
    doc += "Signed post-increment loads (8..10) require MICA 2.0 and use only the long encoding. "
    doc += (
        "Extended majors 12 through 15 and all unallocated subopcodes are reserved.\n"
    )
    doc += "\n## MICA-2C additional short R encodings\n\n"
    doc += "Only legal in MICA 2.0, with the 2C feature bit enabled. "
    doc += "See [MICA2.md](MICA2.md) for full exceptions and writeback rules.\n\n"
    doc += "| op8 | Mnemonic | Operand fields | Meaning |\n| ---: | --- | --- | --- |\n"
    for name, value in compact["opcodes"].items():
        if isinstance(value, list):
            assert len(value) == 8 and value == list(range(value[0], value[0] + 8))
            doc += f"| {value[0]}..{value[-1]} | `{name}` | d3, signed halfword displacement6 | Decrement and branch when nonzero; no x0 counter. |\n"
        elif name == "ldsp":
            doc += f"| {value} | `ldsp d,[sp+offset]` | d3, unsigned slot3 | Read XLEN bits at SP + slot * XLEN/8. |\n"
        elif name == "stsp":
            doc += f"| {value} | `stsp d,[sp+offset]` | d3, unsigned slot3 | Store XLEN bits at SP + slot * XLEN/8. |\n"
        elif name == "stop":
            doc += f"| {value} | `stop` | d3=0, s3=0 | Terminal debug halt until reset. |\n"
        else:
            raise ValueError(f"Unknown 2C mnemonic {name}")
    assert len(set([31, 32, 41] + compact["opcodes"]["dbnz.s"])) == 11
    relocation = compact["relative_branch_relocation"]
    doc += (
        f"\n`dbnz.s` symbol operands use ELF `{relocation['name']}` "
        f"(ID {relocation['id']}), relative to `{relocation['base']}` in "
        f"{relocation['scale']}-byte units. Local and external labels retain the "
        "two-byte encoding; out-of-range or unaligned targets are link errors.\n"
    )
    doc += "\nMICA 2.0 `wfi` retires then sleeps until a wake event. "
    doc += "On the minimal profile, it does not require the T trap extension. "
    doc += "`stop` is the explicit debug/terminal halt instruction.\n"

    profile_h = (
        banner
        + "#pragma once\n#include <array>\n#include <string_view>\nnamespace mica {\nstruct Profile {std::string_view name; int width; unsigned features; bool runnable;};\ninline constexpr std::array<Profile,"
        + str(len(profiles))
        + "> profiles={{\n"
    )
    feature_bits = {
        "X": 1,
        "M": 2,
        "F": 4,
        "A": 8,
        "V": 16,
        "B": 32,
        "T": 64,
        "2C": 256,
    }
    for name, profile in profiles.items():
        features = sum(feature_bits[x] for x in profile["extensions"])
        runnable = "false" if profile["status"].startswith("proposal") else "true"
        profile_h += f'  {{"{name}", {profile["xlen"]}, {features}, {runnable}}},\n'
    profile_h += "}};\n} // namespace mica\n"
    return {
        "isa/generated/assembler.inc": asm,
        "isa/generated/disassembler.inc": dis,
        "isa/generated/mica_isa.svh": sv,
        "docs/architecture/ENCODINGS.md": doc,
        "isa/generated/profiles.hpp": profile_h,
        "isa/generated/encoding_patterns.json": json.dumps(envelopes, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"stale generated file: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
